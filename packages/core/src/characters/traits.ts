/** Case-insensitive prefix-and-substring search over one family (the chip autocomplete). */
export function searchTraits(family: TraitFamily, query: string, limit = 8): string[] {
  const trimmed = query.trim().toLowerCase();
  const all = TRAIT_LISTS[family];
  if (trimmed.length === 0) return all.slice(0, limit);
  const prefix: string[] = [];
  const contains: string[] = [];
  for (const entry of all) {
    const lower = entry.toLowerCase();
    if (lower.startsWith(trimmed)) prefix.push(entry);
    else if (lower.includes(trimmed)) contains.push(entry);
  }
  return [...prefix, ...contains].slice(0, limit);
}
